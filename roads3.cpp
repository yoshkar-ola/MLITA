#include <fstream>
#include <queue>
#include <utility>
#include <vector>

int main() {
    std::ifstream in("INPUT.TXT");
    std::ofstream out("OUTPUT.TXT");

    int n, m, k;
    in >> n >> m >> k;

    std::vector<std::vector<std::pair<int, int>>> g(static_cast<size_t>(n) + 1);
    //2 * m / max(1, n) + 4 
    const size_t est_deg =
        static_cast<size_t>(2 * static_cast<long long>(m) / std::max(1, n)) + 4U;
    for (int v = 1; v <= n; ++v) {
        g[static_cast<size_t>(v)].reserve(est_deg);
    }

    for (int i = 0; i < m; ++i) {
        int a, b, len;
        in >> a >> b >> len;
        g[static_cast<size_t>(a)].push_back({b, len});
        //g[static_cast<size_t>(b)].push_back({a, len});
    }

    std::vector<int> cnt(static_cast<size_t>(n) + 1, 0);
    std::vector<std::vector<long long>> best(static_cast<size_t>(n) + 1);
    for (int v = 1; v <= n; ++v) {
        best[static_cast<size_t>(v)].reserve(static_cast<size_t>(k));
    }

    using Node = std::pair<long long, int>;
    std::priority_queue<Node, std::vector<Node>, std::greater<Node>> pq;
    pq.push({0LL, 1});

    while (!pq.empty()) {
        const long long d = pq.top().first;
        const int u = pq.top().second;
        pq.pop();

        if (cnt[static_cast<size_t>(u)] == k) {
            continue;
        }
        ++cnt[static_cast<size_t>(u)];
        best[static_cast<size_t>(u)].push_back(d);

        for (const auto& e : g[static_cast<size_t>(u)]) {
            const int v = e.first;
            const int w = e.second;
            pq.push({d + static_cast<long long>(w), v});
        }
    }

    for (int city = 2; city <= n; ++city) {
        const auto& v = best[static_cast<size_t>(city)];
        if (v.empty()) {
            out << "0\n";
        } else {
            for (size_t i = 0; i < v.size(); ++i) {
                if (i) {
                    out << ' ';
                }
                out << v[i];
            }
            out << '\n';
        }
    }

    return 0;
}
